import { test, expect } from "@playwright/test";
test("dashboard, navigation, source evidence, review, immutable export", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "Every field, accounted for." })).toBeVisible();
  await expect(page.getByText("DEMO MODE", { exact: true })).toBeVisible();
  await page.screenshot({ path: "test-results/overview-desktop.png", fullPage: true });
  await page.getByRole("button", { name: "View documents", exact: true }).click();
  await page.getByLabel("Filter document library").fill("first_national_bank_rates_page1");
  await expect(page.getByText("1–1 of 1 documents")).toBeVisible();
  await page.getByRole("button", { name: /first_national_bank_rates_page1.pdf/ }).first().click();
  await expect(page.getByText("Source document", { exact: true })).toBeVisible();
  await expect(page.locator(".evidence-box")).toBeVisible();
  await page.screenshot({ path: "test-results/evidence-desktop.png", fullPage: true });
  await page.getByRole("button", { name: "Review field", exact: true }).click();
  await page.getByLabel("Corrected value").fill("1.080");
  await page.getByLabel("Reason").fill("Demo correction for version and export verification.");
  await page.getByRole("button", { name: "Save decision" }).click();
  await expect(page.getByRole("dialog")).not.toBeVisible();
  await expect(page.locator(".field-row.active")).toContainText("1.080%");
  await page.getByRole("button", { name: "history", exact: true }).click();
  await expect(page.locator(".field-history")).toContainText("1.162 → 1.080");
  await page.getByRole("button", { name: "evidence", exact: true }).click();
  await expect(page.locator(".evidence-details")).toContainText("1.162");
  await page.reload();
  await expect(page.locator(".field-row.active")).toContainText("1.080%");
  await page.getByRole("button", { name: "Export results" }).click();
  await page.getByLabel("Immutable result version").selectOption("1");
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export CSV", exact: true }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toContain("v1.csv");
  const stream = await download.createReadStream();
  let text = ""; for await (const chunk of stream!) text += chunk.toString();
  expect(text).toContain('"1.162"');
  expect(text).not.toContain('"1.080"');
  expect(errors).toEqual([]);
});
test("upload guards, review filters and unknown benchmarks", async ({ page }) => {
  await page.goto("/");
  await page.getByRole("button", { name: "Upload document", exact: true }).first().click();
  await page.getByLabel("Choose document file").setInputFiles({ name: "bad.exe", mimeType: "application/octet-stream", buffer: Buffer.from("bad") });
  await expect(page.getByRole("alert")).toContainText("Choose a PDF");
  await page.getByLabel("Choose document file").setInputFiles({ name: "sample.pdf", mimeType: "application/pdf", buffer: Buffer.from("%PDF-1.7") });
  await expect(page.getByRole("button", { name: "Start extraction" })).toBeDisabled();
  await page.getByRole("button", { name: "Close dialog" }).click();
  await page.getByRole("link", { name: /Review queue/ }).click();
  await page.getByRole("button", { name: "Blocking failures", exact: true }).click();
  await expect(page.locator(".review-table tbody tr")).toHaveCount(10);
  await page.getByRole("link", { name: "Evaluation", exact: true }).click();
  await expect(page.getByRole("button", { name: "Run benchmark" })).toBeDisabled();
  await expect(page.getByText("Not measured without ground truth")).toBeVisible();
});
test("mobile navigation, layout and keyboard-accessible modal", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "Every field, accounted for." })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: "test-results/overview-mobile.png", fullPage: true });
  await page.getByRole("button", { name: "Open navigation", exact: true }).click();
  await page.getByRole("link", { name: "Documents", exact: true }).click();
  await expect(page.getByRole("heading", { name: "The source of every answer." })).toBeVisible();
  await page.getByRole("button", { name: "Upload document", exact: true }).click();
  await expect(page.getByRole("dialog")).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(page.getByRole("dialog")).not.toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});
